export type TranslationKey = keyof typeof fr

interface I18nContextValue {
  lang: Language
  locale: string
  setLang: (lang: Language) => void
  hasStoredPreference: boolean
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)
const STORAGE_KEY = 'gamestats-lang'

function interpolate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

function readStoredLanguage(): Language | null {
  try {
    const value = localStorage.getItem(STORAGE_KEY)
    return value === 'fr' || value === 'en' ? value : null
  } catch {
    return null
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const stored = readStoredLanguage()
  const [lang, setLangState] = useState<Language>(stored ?? 'fr')
  const [hasStoredPreference, setHasStoredPreference] = useState(stored !== null)

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const setLang = (next: Language) => {
    setLangState(next)
    setHasStoredPreference(true)
    try {
      localStorage.setItem(STORAGE_KEY, next)
    } catch {
      // Storage unavailable: keep the language for the current session.
    }
  }

  const value = useMemo<I18nContextValue>(() => {
    const dictionary = lang === 'fr' ? fr : en
    const locale = lang === 'fr' ? 'fr-FR' : 'en-US'
    const t = (key: TranslationKey, vars: Record<string, string | number> = {}) => {
      const entry: Translation = dictionary[key] ?? fr[key] ?? key
      const template =
        typeof entry === 'string'
          ? entry
          : Number(vars.count) === 1
            ? entry.one
            : entry.other
      return interpolate(template, vars)
    }
    return { lang, locale, setLang, hasStoredPreference, t }
  }, [lang, hasStoredPreference])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (context === null) {
    throw new Error('useI18n must be used inside I18nProvider')
  }
  return context
}
